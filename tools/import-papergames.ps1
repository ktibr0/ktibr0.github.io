param(
  [string]$SourceRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../_work/upstream-source'))
)

$ErrorActionPreference = 'Stop'
$source = [System.IO.Path]::GetFullPath($SourceRoot)
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$target = Join-Path $repo 'papergames'
$commit = 'dc564a8a24b4e7bb08f32c0952f19982bc733877'

if (-not (Test-Path -LiteralPath $source)) {
  $work = Join-Path $repo '_work'
  $archive = Join-Path $work "papergames-$commit.tar.gz"
  New-Item -ItemType Directory -Force -Path $work | Out-Null
  if (-not (Test-Path -LiteralPath $archive)) {
    Invoke-WebRequest -Uri "https://codeload.github.com/YourChaosChris/PaperGames/tar.gz/$commit" -OutFile $archive
  }
  New-Item -ItemType Directory -Force -Path $source | Out-Null
  & tar.exe -xzf $archive -C $source --strip-components=1
  if ($LASTEXITCODE -ne 0) { throw 'Could not extract the pinned PaperGames archive.' }
}

$games = @('sudoku', 'nonogram', 'kakuro', 'hashi', 'skyscrapers', 'klondike', 'freecell')
$shared = @(
  'ai-pacing.js', 'board-a11y.js', 'card-faces.js', 'confirm-actions.js',
  'daily-challenge.js', 'density.js', 'error-banner.js', 'font-size-toggle.js',
  'game-stats.js', 'game-storage.js', 'high-contrast.js', 'hint-engine.js',
  'i18n.js', 'print-puzzle.js', 'quick-rules.js', 'random-start.js',
  'result-modal.js', 'rules-link.js', 'settings-menu.js', 'storage-warning.js',
  'style.css', 'favicon.png', 'icon-192.png', 'LICENSE', 'NOTICE'
)

New-Item -ItemType Directory -Force -Path $target | Out-Null
foreach ($file in $shared) {
  Copy-Item -LiteralPath (Join-Path $source $file) -Destination (Join-Path $target $file) -Force
}
Copy-Item -LiteralPath (Join-Path $source 'manifest.json') -Destination (Join-Path $target 'manifest.json') -Force
Copy-Item -LiteralPath (Join-Path $source 'i18n-text.js') -Destination (Join-Path $target 'i18n-text.js') -Force
New-Item -ItemType Directory -Force -Path (Join-Path $target 'lang') | Out-Null
Copy-Item -LiteralPath (Join-Path $source 'lang/ru.js') -Destination (Join-Path $target 'lang/ru.js') -Force
Copy-Item -LiteralPath (Join-Path $source 'lang/ru-text.js') -Destination (Join-Path $target 'lang/ru-text.js') -Force

foreach ($game in $games) {
  $files = @("$game.html", "$game-rules.html", "$game-app.js", "$game-core.js")
  foreach ($file in $files) {
    Copy-Item -LiteralPath (Join-Path $source $file) -Destination (Join-Path $target $file) -Force
  }
  $puzzles = Join-Path $source "$game-puzzles.js"
  if (Test-Path -LiteralPath $puzzles) {
    Copy-Item -LiteralPath $puzzles -Destination (Join-Path $target "$game-puzzles.js") -Force
  }
}

# Retain the original game and app sources. These are integration adapters around
# the upstream engine; no unrelated game is exposed in the local game switcher.
foreach ($game in $games) {
  foreach ($page in @("$game.html", "$game-rules.html")) {
    $path = Join-Path $target $page
    $html = Get-Content -LiteralPath $path -Raw
    $html = [regex]::Replace($html, '(?is)\s*<script>\(function\(\)\{var b="https://yourchaoschris\.github\.io/PaperGames/.*?</script>', '')
    $html = [regex]::Replace($html, '(?is)\s*<!-- seo: generated by tools/seo\.js.*?<!-- /seo -->', '')
    $html = [regex]::Replace($html, '(?is)<link rel="alternate"[^>]*>\s*', '')
    $html = [regex]::Replace($html, '(?is)<meta (?:property="(?:og:[^"]+|twitter:[^"]+)"|name="twitter:[^"]+")[^>]*>\s*', '')
    $html = $html.Replace('<html lang="en">', '<html lang="ru">')
    $html = $html.Replace('<link rel="stylesheet" href="style.css">', '<link rel="stylesheet" href="style.css">' + [Environment]::NewLine + '  <link rel="stylesheet" href="../library/papergames-game.css">')
    $html = $html.Replace('href="about.html" class="app-title-author app-title-author-link">by Christopher Müller</a>', 'href="credits.html" class="app-title-author app-title-author-link papergames-credit">PaperGames · Christopher Müller</a>')
    $html = $html.Replace('href="credits.html" class="app-title-author app-title-author-link papergames-credit">PaperGames · Christopher Müller</a>', 'href="credits.html" class="app-title-author app-title-author-link papergames-credit">Christopher Müller</a>')
    $html = [regex]::Replace($html, '(?is)<script>try\{if\(\(\(\s*/\[\?&\]lang=.*?</script>', '<script>try{var m=/[?&]lang=([a-z]{2})/.exec(location.search);var l=(m&&m[1])||localStorage.getItem("einkchess_lang")||"ru";if(l!=="en"){document.documentElement.classList.add("i18n-pending");setTimeout(function(){document.documentElement.classList.remove("i18n-pending")},4000)}}catch(e){}</script>')
    $nav = '<nav class="site-nav">' + [Environment]::NewLine +
      '    <a href="index.html" class="site-nav-link">Игротека</a>' + [Environment]::NewLine +
      "    <a href=`"$($game)-rules.html`" class=`"site-nav-link`">Правила</a>" + [Environment]::NewLine +
      '  </nav>'
    $html = [regex]::Replace($html, '(?s)<nav class="site-nav">.*?</nav>', $nav)
    $html = [regex]::Replace($html, '(?s)<footer class="site-footer">.*?</footer>', '<footer class="site-footer papergames-footer"><a class="library-back" href="index.html">В Игротеку</a><div class="papergames-credit">© 2025 <a href="https://github.com/YourChaosChris">Christopher Müller</a> · <a href="https://github.com/YourChaosChris/PaperGames">исходный проект</a> · <a href="credits.html">автор и лицензии</a></div><div class="library-offline"><button type="button" id="library-offline-save">Сохранить для игры без интернета</button><p id="library-offline-status" data-state="idle" role="status" aria-live="polite">Офлайн-копия не проверена.</p><small>Сохраняются только семь новых игр. Добавьте Игротеку на главный экран, чтобы открыть их без сети.</small></div></footer>')
    $html = [regex]::Replace($html, '(?m)^<script src="(?:force-update|offline-status|sw-register|update-banner|game-switcher)\.js"></script>\r?\n?', '')
    $footerScript = "<script src=`"sw-register.js`"></script>`n<script src=`"../library/force-update.js`"></script>`n<script src=`"../library/offline.js`"></script>`n"
    $html = $html.Replace('</body>', "$footerScript</body>")
    Set-Content -LiteralPath $path -Value $html -NoNewline -Encoding utf8
  }
}

$i18nPath = Join-Path $target 'i18n.js'
$i18n = Get-Content -LiteralPath $i18nPath -Raw
$i18n = $i18n.Replace('function detectBrowserLang() {', 'function detectBrowserLang() {')
$i18n = [regex]::Replace($i18n, '(?s)function detectBrowserLang\(\) \{.*?\n  \}', "function detectBrowserLang() {$([Environment]::NewLine)    return `"ru`";$([Environment]::NewLine)  }", 1)
$i18n = $i18n.Replace('const LANGUAGE_ORDER = ["en", "de", "fr", "es", "it", "nl", "pl", "uk", "ru", "ja", "zh", "ar"];', 'const LANGUAGE_ORDER = ["ru", "en"];')
$i18n = $i18n.Replace('return m && LANGUAGE_NAMES[m[1]] ? m[1] : null;', 'return m && ["ru", "en"].includes(m[1]) ? m[1] : null;')
$i18n = $i18n.Replace('if (saved && LANGUAGE_NAMES[saved]) return saved;', 'if (saved && ["ru", "en"].includes(saved)) return saved;')
$i18n = $i18n.Replace('return lang === DEFAULT_LANG ? scriptBase + "i18n-text.js" : scriptBase + "lang/" + lang + "-text.js";', 'return lang === "en" ? scriptBase + "i18n-text.js" : scriptBase + "lang/" + lang + "-text.js";')
Set-Content -LiteralPath $i18nPath -Value $i18n -NoNewline -Encoding utf8

$manifest = @{
  name = 'Игротека PaperGames'
  short_name = 'Игротека'
  start_url = './index.html'
  scope = './'
  display = 'standalone'
  background_color = '#ffffff'
  theme_color = '#ffffff'
  icons = @(
    @{ src = './icon-192.png'; sizes = '192x192'; type = 'image/png' }
  )
} | ConvertTo-Json -Depth 5
Set-Content -LiteralPath (Join-Path $target 'manifest.json') -Value $manifest -Encoding utf8

$sourceFiles = @{}
$imported = [System.Collections.Generic.List[string]]::new()
$imported.AddRange([string[]]$shared)
$imported.Add('manifest.json')
$imported.Add('i18n-text.js')
$imported.Add('lang/ru.js')
$imported.Add('lang/ru-text.js')
foreach ($game in $games) {
  $imported.Add("$game.html")
  $imported.Add("$game-rules.html")
  $imported.Add("$game-app.js")
  $imported.Add("$game-core.js")
  if (Test-Path -LiteralPath (Join-Path $source "$game-puzzles.js")) { $imported.Add("$game-puzzles.js") }
}
foreach ($file in $imported) {
  $sourcePath = Join-Path $source $file
  $targetFile = if ($file -eq 'i18n.js') { 'i18n.js' } else { $file }
  $sourceFiles[$targetFile] = @{
    upstreamPath = $file
    gitBlob = (& git -C $repo hash-object -- $sourcePath).Trim()
  }
}

$provenance = @{
  project = 'PaperGames by Christopher Müller'
  repository = 'https://github.com/YourChaosChris/PaperGames'
  commit = $commit
  archive = "https://codeload.github.com/YourChaosChris/PaperGames/tar.gz/$commit"
  archiveSha256 = 'C8EBE4969F00771EEF64C46CD9116250A4ECC93E82B9ED039B270D515B68CE2D'
  selectedGames = $games
  sourceFiles = $sourceFiles
  adaptations = @(
    'Only the seven selected game pages, rules, app handlers, game cores, puzzle data, common helpers, and Russian translation are included.',
    'Engine and app-handler JavaScript remain unchanged. Game and rules HTML use local navigation, Russian by default, local credits, and the scoped offline controls.',
    'i18n.js keeps English as its internal source-language constant; the local integration defaults to Russian and offers only Russian and English.',
    'The local catalog is generated from the root catalog, with old game routes made relative and font requests made optional through system fallbacks.',
    'The service worker is locally written and registered only with /papergames/ scope; no upstream worker or forced reload behavior is used.'
  )
} | ConvertTo-Json -Depth 8
Set-Content -LiteralPath (Join-Path $target 'UPSTREAM.json') -Value $provenance -Encoding utf8

# Generate the offline catalog from the root catalog so its cards and order stay aligned.
$catalog = Get-Content -LiteralPath (Join-Path $repo 'index.html') -Raw
$catalog = [regex]::Replace($catalog, '(?im)^\s*<link rel="preconnect"[^>]*>\s*', '')
$catalog = [regex]::Replace($catalog, '(?im)^\s*<link href="https://fonts\.googleapis\.com[^"]*" rel="stylesheet">\s*', '')
$catalog = $catalog.Replace('href="library/catalog.css"', 'href="../library/catalog.css"')
$catalog = $catalog.Replace('href="papergames/manifest.json"', 'href="manifest.json"')
$catalog = $catalog.Replace('href="papergames/credits.html"', 'href="credits.html"')
foreach ($game in $games) { $catalog = $catalog.Replace("href=`"papergames/$game.html`"", "href=`"$game.html`"") }
$catalog = $catalog.Replace('href="cryptographer/index.html"', 'href="../cryptographer/index.html"')
$catalog = $catalog.Replace('href="rsvp/index.html"', 'href="../rsvp/index.html"')
$catalog = $catalog.Replace('href="jellybattle/index.html"', 'href="../jellybattle/index.html"')
$catalog = $catalog.Replace('href="sumplete/index.html"', 'href="../sumplete/index.html"')
$catalog = $catalog.Replace('src="papergames/sw-register.js"', 'src="sw-register.js"')
$catalog = $catalog.Replace('src="library/force-update.js"', 'src="../library/force-update.js"')
$catalog = $catalog.Replace('src="library/offline.js"', 'src="../library/offline.js"')
Set-Content -LiteralPath (Join-Path $target 'index.html') -Value $catalog -NoNewline -Encoding utf8

Write-Output "Imported seven PaperGames modules from $commit into papergames/."
